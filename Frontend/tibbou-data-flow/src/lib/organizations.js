// Client-side mirrors of small, stable backend rules -- purely for instant UX
// feedback (a slug preview, a "you can't claim gmail.com" hint, an instant
// dbt resource count on file select). None of these are security boundaries;
// the backend re-derives and enforces the real values independently
// (Backend/app/services/organizations.py, Backend/app/services/ingestion.py).

const FREE_EMAIL_DOMAINS = new Set([
  "gmail.com",
  "outlook.com",
  "hotmail.com",
  "yahoo.com",
  "icloud.com",
  "proton.me",
  "protonmail.com",
]);

// Mirrors Backend/app/services/ingestion.py's DBT_RESOURCE_TYPES.
const DBT_RESOURCE_TYPES = new Set(["model", "source", "seed", "snapshot"]);

export function emailDomain(email) {
  if (!email || !email.includes("@")) return null;
  const domain = email.trim().toLowerCase().split("@").pop();
  return domain || null;
}

export function isFreeEmailDomain(domain) {
  return domain ? FREE_EMAIL_DOMAINS.has(domain) : false;
}

export function slugPreview(name) {
  const base = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return base || "organization";
}

export function countDbtResources(manifest) {
  let count = 0;
  for (const collection of ["nodes", "sources"]) {
    const entries = manifest?.[collection];
    if (!entries || typeof entries !== "object") continue;
    for (const node of Object.values(entries)) {
      if (node && DBT_RESOURCE_TYPES.has(node.resource_type) && node.name) {
        count += 1;
      }
    }
  }
  return count;
}

// Tibbou only reads usage metadata from the shared SNOWFLAKE database, so the
// role gets no access to any of the customer's own data. The login key is
// generated by Tibbou and registered in a later step, not here.
export function leastPrivilegeSql({ roleName, warehouseName, userName }) {
  const role = (roleName || "TIBBOU_READER").trim().toUpperCase();
  const warehouse = (warehouseName || "").trim().toUpperCase();
  const user = (userName || "TIBBOU_SVC").trim().toUpperCase();
  const identifier = /^[A-Za-z_][A-Za-z0-9_$]{0,254}$/;
  const blocked = ["ACCOUNTADMIN", "ORGADMIN", "SECURITYADMIN", "SYSADMIN", "USERADMIN", "PUBLIC"];
  if (![role, warehouse, user].every((value) => identifier.test(value)) || blocked.includes(role)) {
    return "-- Enter a dedicated service user, limited role, and warehouse using simple Snowflake identifiers.";
  }
  return `-- Have a Snowflake administrator review this for a dedicated service user.
CREATE ROLE IF NOT EXISTS "${role}";
GRANT USAGE ON WAREHOUSE "${warehouse}" TO ROLE "${role}";
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE "${role}";
-- Optional, when Access History is available and dataset attribution is desired:
-- GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE "${role}";
CREATE USER IF NOT EXISTS "${user}" TYPE = SERVICE DEFAULT_ROLE = "${role}" DEFAULT_WAREHOUSE = "${warehouse}";
GRANT ROLE "${role}" TO USER "${user}";`;
}
